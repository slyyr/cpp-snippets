#include <iostream>
using namespace std;

int main() {
    int a = 70, b = 30;

    cout << "numbers = " << a<< " and " << b;

    cout << "\naddition" << "\t" << a+b;
    cout << "\nsubstraction" << "\t" << a-b;
    cout << "\nmultiplication" << "\t" << a*b;
    cout << "\ndivision" << "\t" << a/b;
    cout << "\nmod" << "\t" << a%b;
    return 0;
}

